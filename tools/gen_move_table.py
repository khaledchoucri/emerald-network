#!/usr/bin/env python3
"""Generate src/pkbn/move_table.c from attacks_curated.py + lanes_curated.py.

usage: python3 tools/gen_move_table.py <pc_port root>
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from attacks_curated import ATTACKS, KINDS
from lanes_curated import MOVES as LANE_MOVES, REMOVED, PROGRAM_ADVANCES
from attacks_curated import PA_EFFECTS
from fx_curated import FX
FXNAMES = [f[0] for f in FX]
import json
# POC-31 (L4a): each ladder move's shared code, open from the start for that move (data/learnset_ladders.json)
LADDER = {}
LADDER_OF = {}   # POC-32 (F1): species -> (code, three moves), for the automatic folder
for line in json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'learnset_ladders.json')))['lines']:
    for step in line['ladder']:
        LADDER.setdefault(step['move'], set()).add(line['letter'])
    for mem in line['members']:
        LADDER_OF[mem['species']] = (line['letter'], [st['move'] for st in line['ladder']])

root = sys.argv[1] if len(sys.argv) > 1 else '.'
bm = open(f'{root}/src/data/battle_moves.h').read()
order = [n[5:] for n in re.findall(r'\[(MOVE_\w+)\]\s*=\s*\{', bm) if n != 'MOVE_NONE']

LANES_MAX = 6   # POC-31: 4 -> 6, room for the ladders' shared codes (L4a)
PATTERNS = {'plus': 'BLAST_PLUS', 'x': 'BLAST_X', 'square': 'BLAST_SQUARE', 'single': 'BLAST_SINGLE'}
FLAGS = {'slow': 'GF_SLOW', 'fast': 'GF_FAST', 'invuln': 'GF_INVULN', 'hold': 'GF_HOLD', 'push': 'GF_PUSH',
         'recharge': 'GF_RECHARGE', 'pull': 'GF_PULL', 'throw': 'GF_THROW'}

def parse_attack(spec):
    toks = spec.split()
    kind, pattern, hits, windup, rows, flags, fx = toks[0], 'BLAST_PLUS', '1', '0', '1', [], '0'
    for t in toks[1:]:
        if t in PATTERNS: pattern = PATTERNS[t]
        elif t in FLAGS: flags.append(FLAGS[t])
        elif t.startswith('hits='):
            v = t[5:]; hits = 'HITS_2_TO_5' if v == '2-5' else 'HITS_PARTY' if v == 'party' else v
        elif t.startswith('charge='): windup = t[7:]
        elif t.startswith('rows='): rows = t[5:]
        elif t.startswith('fx='):
            if t[3:] not in FXNAMES: raise SystemExit(f'unknown fx {t} in {spec} (tools/fx_curated.py)')
            fx = f'FX_{t[3:]} + 1'
        else: raise SystemExit(f'unknown modifier {t} in {spec}')
    return kind, pattern, hits, windup, rows, ' | '.join(flags) or '0', fx

def parse_lanes(spec):
    out = []
    for t in spec.split():
        out.append('LANE_WILD' if t == '*' else f"LANE('{t[0]}')")
    return out

lines = ['// GENERATED by tools/gen_move_table.py from tools/attacks_curated.py and tools/lanes_curated.py.',
         '// Do not edit by hand: change the curated files and regenerate.',
         '#include "global.h"', '#include "constants/battle.h"', '#include "constants/moves.h"', '#include "constants/pokemon.h"', '#include "pkbn/move_table.h"', '#include "pkbn/fx_ids.h"', '#include "constants/species.h"', '',
         'const struct PkbnMoveInfo gPkbnMoveInfo[MOVES_COUNT] =', '{']
for m in order:
    kind, pattern, hits, windup, rows, flags, fx = parse_attack(ATTACKS[m])
    removed = m in REMOVED
    lanes = [] if removed or m not in LANE_MOVES else parse_lanes(LANE_MOVES[m])
    lanes_c = '{' + ', '.join(lanes) + '}' if lanes else '{0}'
    if len(lanes) > LANES_MAX: raise SystemExit(f'{m}: {len(lanes)} codes, at most {LANES_MAX}')
    lad = ' | '.join(f"LADDER('{c}')" for c in sorted(LADDER.get(m, ()))) if lanes else ''
    lines.append(f'    [MOVE_{m}] = {{ GK_{kind}, {pattern}, {hits}, {windup}, {rows}, {flags}, {len(lanes)}, {lanes_c}'
                 + (f', {fx}' if fx != '0' or lad else '') + (f', {lad}' if lad else '') + ' },'
                 + ('  // removed (review)' if removed else ''))
lines.append('};')
lines.append('')
lines.append('// POC-32 (F1): each Hoenn line\'s ladder (data/learnset_ladders.json), for the automatic folder')
lines.append('const struct PkbnLadder gPkbnLadderOf[NUM_SPECIES] =')
lines.append('{')
for sp in sorted(LADDER_OF):
    c, ms = LADDER_OF[sp]
    lines.append(f"    [SPECIES_{sp}] = {{ LANE('{c}'), {{{', '.join('MOVE_' + m for m in ms)}}} }},")
lines.append('};')
lines.append('')
lines.append('const char *const gPkbnKindNames[GK_COUNT] =')
lines.append('{')
for k in KINDS:
    lines.append(f'    [GK_{k}] = "{k}",')
lines.append('};')
PAF = {'crit': 'PAF_CRIT', 'partyheal': 'PAF_PARTYHEAL', 'hitonce': 'PAF_HITONCE', 'nofaint': 'PAF_NOFAINT',
       'speeddown': 'PAF_SPEEDDOWN', 'accdown': 'PAF_ACCDOWN', 'fast': 'PAF_FAST', 'panels=crack': 'PAF_PANEL_CRACK',
       'panels=poison': 'PAF_PANEL_POISON'}
STATUS = {'BRN': 'STATUS1_BURN', 'PAR': 'STATUS1_PARALYSIS', 'FRZ': 'STATUS1_FREEZE', 'TOX': 'STATUS1_TOXIC_POISON',
          'CONF': 'PA_CONFUSE'}
lines.append('')
lines.append('const struct PkbnProgramAdvance gPkbnProgramAdvances[PKBN_PA_COUNT] =')
lines.append('{')
for name, recipe, sketch in PROGRAM_ADVANCES:
    toks = PA_EFFECTS[name].split()
    kv = dict(t.split('=', 1) for t in toks[1:] if '=' in t and not t.startswith('panels='))
    flags = [PAF[t] for t in toks[1:] if t in PAF]
    st = STATUS[kv['status']] if 'status' in kv else '0'
    rec = ', '.join('MOVE_' + m for m in recipe)
    lines.append(f'    {{ "{name}", {{{rec}}}, GK_{toks[0]}, TYPE_{kv["type"]}, {kv["power"]}, {kv.get("rows", "1")}, '
                 f'{kv.get("hits", "1")}, {" | ".join(flags) or "0"}, {st}, {kv.get("drain", "0")} }}, // {sketch}')
lines.append('};')
open(f'{root}/src/pkbn/move_table.c', 'w').write('\n'.join(lines) + '\n')

h = ['// GENERATED by tools/gen_move_table.py. Kinds are documented in tools/attacks_curated.py (KINDS).',
     '#ifndef GUARD_PKBN_MOVE_TABLE_H', '#define GUARD_PKBN_MOVE_TABLE_H', '', 'enum', '{']
for k, (desc, bn) in KINDS.items():
    h.append(f'    GK_{k}, // {desc}' + (f' [{bn}]' if bn else ''))
h += ['    GK_COUNT', '};', '',
      'enum { BLAST_PLUS, BLAST_X, BLAST_SQUARE, BLAST_SINGLE };', '',
      '#define HITS_2_TO_5 254 // Gen 3 multi-hit odds',
      '#define HITS_PARTY  255 // Beat Up: one hit per healthy party member', '',
      '#define GF_SLOW     (1 << 0)',
      '#define GF_FAST     (1 << 1)',
      '#define GF_INVULN   (1 << 2)',
      '#define GF_HOLD     (1 << 3)',
      '#define GF_PUSH     (1 << 4)',
      '#define GF_RECHARGE (1 << 5)',
      '#define GF_PULL     (1 << 6)   // POC-26: drags the target one panel toward the user',
      '#define GF_THROW    (1 << 7)   // POC-26: drops the target in its back column on another row', '',
      "#define LANE(c)   ((c) - 'A')",
      "#define LADDER(c) (1u << ((c) - 'A'))",
      '#define LANE_WILD 26', '',
      'struct PkbnMoveInfo',
      '{',
      '    u8 kind;',
      '    u8 pattern;   // BOMB blast pattern',
      '    u8 hits;      // 1.., HITS_2_TO_5, HITS_PARTY',
      '    u8 windup;    // charge frames before it fires',
      '    u8 rows;      // CANNON / WAVE / SHOCKWAVE: 1 or 3',
      '    u8 flags;     // GF_*',
      '    u8 laneCount; // 0 = not a chip (removed by review or not on the grid)',
      f'    u8 lanes[{LANES_MAX}];  // one letter per copy, in order; LANE_WILD = *',
      '    u8 fx;        // POC-31 (M4a): FX_* + 1 drawn on impact in the type\'s colours (0 = the type\'s own picture)',
      '    u32 ladder;   // POC-31 (L4a): codes this move shares with its ladder - open from the start for it (LADDER(c))',
      '};', '',
      'extern const struct PkbnMoveInfo gPkbnMoveInfo[];', '',
      '// POC-32 (F1): a species\' ladder (moves[0] = MOVE_NONE: none)',
      'struct PkbnLadder { u8 code; u16 moves[3]; };',
      'extern const struct PkbnLadder gPkbnLadderOf[];', '',
      '// Program Advances (tools/lanes_curated.py PROGRAM_ADVANCES + tools/attacks_curated.py PA_EFFECTS)',
      f'#define PKBN_PA_COUNT {len(PROGRAM_ADVANCES)}',
      '#define PA_CONFUSE       0xFFFFFFFF // pseudo-status: confusion',
      '#define PAF_CRIT         (1 << 0)',
      '#define PAF_PARTYHEAL    (1 << 1)',
      '#define PAF_HITONCE      (1 << 2)',
      '#define PAF_NOFAINT      (1 << 3)',
      '#define PAF_SPEEDDOWN    (1 << 4)',
      '#define PAF_ACCDOWN      (1 << 5)',
      '#define PAF_FAST         (1 << 6)',
      '#define PAF_PANEL_CRACK  (1 << 7)',
      '#define PAF_PANEL_POISON (1 << 8)',
      'struct PkbnProgramAdvance',
      '{',
      '    const char *name;',
      '    u16 recipe[3];   // in order, consecutive in one Custom selection',
      '    u8 kind;         // GK_*',
      '    u8 type;',
      '    u16 power;',
      '    u8 rows, hits;',
      '    u16 flags;       // PAF_*',
      '    u32 status;      // STATUS1_* (or PA_CONFUSE) applied on hit, 100%',
      '    u8 drain;        // % of damage healed',
      '};',
      'extern const struct PkbnProgramAdvance gPkbnProgramAdvances[];',
      '// POC-20a: index PKBN_PA_COUNT is the Unison pair\'s Program Advance, built when a Unison starts (grid_battle.c)',
      '#define PA_UNISON PKBN_PA_COUNT',
      'extern struct PkbnProgramAdvance gPkbnUnisonPA;',
      '// POC-20c: indices PA_UNISON + 1 ... are the Dark Chips (include/pkbn/dark.h, gPkbnDarkPA)',
      'extern const struct PkbnProgramAdvance *Pkbn_DarkPA(u8 i);',
      '// POC-22a: after the 5 Dark Chips (DARK_GIVERS), the type trios being formed: one per Program Advance slot',
      '#define PA_TRIO (PA_UNISON + 1 + 5)',
      '#define PA_TRIO_SLOTS 2',
      'extern struct PkbnProgramAdvance gPkbnTrioPA[PA_TRIO_SLOTS];',
      '#define PKBN_PA(i) (*((i) >= PA_TRIO ? &gPkbnTrioPA[((i) - PA_TRIO) % PA_TRIO_SLOTS] \\',
      '                   : (i) == PKBN_PA_COUNT ? &gPkbnUnisonPA \\',
      '                   : (i) > PKBN_PA_COUNT ? Pkbn_DarkPA((i) - PKBN_PA_COUNT - 1) : &gPkbnProgramAdvances[(i)]))',
      'extern const char *const gPkbnKindNames[];', '',
      '#endif // GUARD_PKBN_MOVE_TABLE_H']
open(f'{root}/include/pkbn/move_table.h', 'w').write('\n'.join(h) + '\n')
print('wrote', len(order), 'moves')
