#!/usr/bin/env python3
"""Generate include/pkbn/bn6_results_data.h: BN6's post-battle results window, from a bn6f checkout (POC-19).

Usage: gen_bn6_results.py <bn6f dir> <out.h>

Everything is inline .byte/.word data in bn6f data/dat38_86.s (no compression); the labels and how BN6 loads them are
in asm/asm03_0.s:12353-12470 (sub_802C34E):
  window tilesets byte_872F3F4 / byte_8730254 / dword_8731154 -> VRAM 0x6008020 (from tile 1),
  window tilemaps dword_8731DF4 / dword_8732154 / dword_87324B4 (24x18 u16 entries each),
  window palettes dword_8732814 (3 x 16 colours -> BG palettes 9-11),
  digit tiles dword_8732874 -> VRAM 0x6009400 (tile 0xA0): digit d = tiles 2d (top) and 2d+1 (bottom), "S" = 22/23,
  zenny reveal picture dword_8732E54 (7x6 tiles) with palette dword_8733394,
  HP reveal picture dword_87333B4 with palette dword_87338F4.
The three windows are "RESULT", "WINNER!" and "LOSER" (checked by rendering them).
Never committed (CLAUDE.md rule 6): the header is built from the user's own bn6f checkout by setup_host.sh.
"""
import os, re, sys

def label_bytes(lines, name):
    for i, l in enumerate(lines):
        if re.match(r'^%s::?(\s|$)' % re.escape(name), l):
            out = bytearray()
            for l2 in lines[i + 1:]:
                l2 = l2.split('//')[0].strip()
                if not l2:
                    continue
                m = re.match(r'\.(byte|hword|word)\s+(.*)', l2)
                if not m:
                    break
                sz = {'byte': 1, 'hword': 2, 'word': 4}[m.group(1)]
                for v in m.group(2).split(','):
                    out += (int(v.strip(), 0) & ((1 << 8 * sz) - 1)).to_bytes(sz, 'little')
            return bytes(out)
    raise KeyError(name)

def carray(f, ctype, name, data, width):
    if width == 2:
        vals = [data[i] | data[i + 1] << 8 for i in range(0, len(data) - 1, 2)]
    else:
        vals = list(data)
    f.write('static const %s %s[%d] = {\n' % (ctype, name, len(vals)))
    for i in range(0, len(vals), 16):
        f.write('    ' + ', '.join(('0x%04X' if width == 2 else '0x%02X') % v for v in vals[i:i + 16]) + ',\n')
    f.write('};\n')

def main():
    root, out = sys.argv[1], sys.argv[2]
    lines = open(os.path.join(root, 'data/dat38_86.s'), errors='replace').read().split('\n')
    with open(out, 'w') as f:
        f.write('// Generated by tools/gen_bn6_results.py from bn6f data/dat38_86.s - do not edit, do not commit.\n')
        f.write('#ifndef GUARD_PKBN_BN6_RESULTS_DATA_H\n#define GUARD_PKBN_BN6_RESULTS_DATA_H\n')
        for k, (ts, tm) in enumerate([('byte_872F3F4', 'dword_8731DF4'), ('byte_8730254', 'dword_8732154'),
                                      ('dword_8731154', 'dword_87324B4')]):
            carray(f, 'u8', 'sBn6ResTiles%d' % k, label_bytes(lines, ts), 1)
            carray(f, 'u16', 'sBn6ResMap%d' % k, label_bytes(lines, tm), 2)
        carray(f, 'u16', 'sBn6ResPal', label_bytes(lines, 'dword_8732814'), 2)
        carray(f, 'u8', 'sBn6ResDigits', label_bytes(lines, 'dword_8732874'), 1)
        carray(f, 'u8', 'sBn6ResZenny', label_bytes(lines, 'dword_8732E54'), 1)
        carray(f, 'u16', 'sBn6ResZennyPal', label_bytes(lines, 'dword_8733394'), 2)
        carray(f, 'u8', 'sBn6ResHP', label_bytes(lines, 'dword_87333B4'), 1)
        carray(f, 'u16', 'sBn6ResHPPal', label_bytes(lines, 'dword_87338F4'), 2)
        f.write('#endif\n')

if __name__ == '__main__':
    main()
